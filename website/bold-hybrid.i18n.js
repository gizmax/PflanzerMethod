  var LANGS = ['en', 'cs', 'de', 'es', 'fr', 'it', 'pl'];
  var KEY = 'pflanzer-lang';

  function applyLang(code) {
    var D = I18N[code];
    if (!D) return;
    document.documentElement.lang = code;
    document.title = D.title;
    document.querySelectorAll('[data-i]').forEach(function (el) {
      var v = D[el.getAttribute('data-i')];
      if (v != null) el.innerHTML = v;
    });
    window.__plantLabels = D.plant;
    if (window.__plantUpdate) window.__plantUpdate();
    try { localStorage.setItem(KEY, code); } catch (e) {}
    document.querySelectorAll('.langs button').forEach(function (b) {
      b.classList.toggle('on', b.dataset.lang === code);
    });
  }

  /* switcher v horní liště */
  var holder = document.getElementById('langs');
  if (holder) {
    LANGS.forEach(function (code) {
      var b = document.createElement('button');
      b.type = 'button';
      b.dataset.lang = code;
      b.textContent = code;
      b.addEventListener('click', function () { applyLang(code); });
      holder.appendChild(b);
    });
  }

  var initial = 'en';
  try {
    var p = new URLSearchParams(location.search).get('lang');
    var saved = localStorage.getItem(KEY);
    if (p && I18N[p]) initial = p;
    else if (saved && I18N[saved]) initial = saved;
  } catch (e) {}
  applyLang(initial);
